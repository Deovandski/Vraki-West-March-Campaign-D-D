#!/usr/bin/env node
/* Bundles every Markdown file in the repo into site/snapshot.js.
   The site normally loads the .md files directly, so it's always current on GitHub Pages.
   The snapshot is the backup for when someone opens index.html straight from their computer
   (browsers block loading files that way). Run it after changing any .md file:
     node site/build-snapshot.js */
const fs = require("fs");
const path = require("path");
const root = path.resolve(__dirname, "..");
const skip = new Set([".git", "node_modules", "site"]);
const docs = {};
(function walk(dir) {
  for (const name of fs.readdirSync(dir).sort()) {
    if (skip.has(name)) continue;
    const full = path.join(dir, name);
    const rel = path.relative(root, full).split(path.sep).join("/");
    if (fs.statSync(full).isDirectory()) walk(full);
    else if (/\.md$/i.test(name)) docs[rel] = fs.readFileSync(full, "utf8").replace(/\r\n?/g, "\n");
  }
})(root);
// The site's own README is the one page inside site/ worth bundling.
const siteReadme = path.join(__dirname, "README.md");
if (fs.existsSync(siteReadme)) docs["site/README.md"] = fs.readFileSync(siteReadme, "utf8").replace(/\r\n?/g, "\n");
const out = "/* Generated by site/build-snapshot.js. Don't edit by hand. */\n" +
  "window.VW = window.VW || {};\nwindow.VW.snapshot = " + JSON.stringify({ builtAt: new Date().toISOString().slice(0, 10), docs }) + ";\n";
fs.writeFileSync(path.join(__dirname, "snapshot.js"), out);
console.log("Wrote site/snapshot.js with " + Object.keys(docs).length + " pages (" + Math.round(out.length / 1024) + " KB).");
